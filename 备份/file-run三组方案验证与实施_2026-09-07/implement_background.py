def change(name, role, replacements, transform=None):
    p=BASE/name; old=p.read_text(encoding='utf-8-sig')
    assert hashlib.sha256(p.read_bytes()).hexdigest()==hashes[p.relative_to(ROOT).as_posix()],f'Concurrent change: {p}'
    s=old
    for a,b in replacements:
        assert a in s, (name,a)
        s=s.replace(a,b)
    if transform:s=transform(s)
    s=re.sub(r'方案版本：\d{4}-\d{2}-\d{2}', '方案版本：2026-09-07',s)
    if '方案版本：2026-09-07' not in s:
        pos=s.index('\n\n',s.index('title:'))
        s=s[:pos]+'\n\n方案版本：2026-09-07'+s[pos:]
    pos=s.index('\n## ')
    s=s[:pos]+'\n## 本背景的责任\n\n'+role+'\n'+s[pos:]
    s=s.rstrip()+'\n'+HANDOFF
    p.write_text(s,encoding='utf-8')

